/**
 * npm run db:push   apply supabase/migrations to the project in SUPABASE_DB_URL
 * npm run db:types  regenerate src/types/database.ts from that project's schema
 *
 * Runs the Supabase CLI directly (no shell), so the database URL's special
 * characters don't need quoting on any OS.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

try {
  process.loadEnvFile(".env.local");
} catch {
  // No .env.local: fall back to the shell environment.
}

const dbUrl = process.env.SUPABASE_DB_URL?.trim();
if (!dbUrl) {
  console.error(
    "✗ SUPABASE_DB_URL is missing. In Supabase: Connect → Session pooler → copy the URI, put your database password in it, and add it to .env.local.",
  );
  process.exit(1);
}

const cli = createRequire(import.meta.url).resolve("supabase/dist/supabase.js");
const command = process.argv[2];

function run(args: string[], capture = false) {
  const result = spawnSync(process.execPath, [cli, ...args], {
    stdio: capture ? ["inherit", "pipe", "inherit"] : "inherit",
    encoding: "utf8",
    env: { ...process.env, SUPABASE_YES: "1" },
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
  return result.stdout ?? "";
}

if (command === "push") {
  run(["db", "push", `--remote=${dbUrl}`, "--yes"]);
} else if (command === "types") {
  const types = run(["gen", "types", "typescript", `--remote=${dbUrl}`, "--schema", "public"], true);
  const out = join(process.cwd(), "src", "types", "database.ts");
  writeFileSync(out, `// Generated by \`npm run db:types\` from the live schema. Do not edit by hand.\n\n${types}`);
  console.log(`✓ Wrote ${out}`);
} else {
  console.error("Usage: node scripts/db.ts <push|types>");
  process.exit(1);
}
